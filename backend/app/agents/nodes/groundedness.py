
from __future__ import annotations

import re
from typing import Any, Dict

from backend.app.rag.evaluation.groundedness import (
    CLAIM_SUPPORT_THRESHOLD,
    evaluate_groundedness,
)


# ============================================================
# CONFIGURATION
# ============================================================

GROUNDEDNESS_THRESHOLD = 0.70
MAX_UNSUPPORTED_CLAIM_RATE = 0.30


# ============================================================
# RESPONSE HELPERS
# ============================================================

def _get_response(
    state: Dict[str, Any],
) -> str:
    """
    Extract the current LLM explanation from graph state.

    Canonical location:
        state["response"]["llm_explanation"]

    Backward-compatible top-level locations are also supported.
    """

    response = state.get("response")

    if isinstance(response, dict):
        for key in (
            "llm_explanation",
            "llm_response",
            "generated_response",
            "explanation",
        ):
            value = response.get(key)

            if isinstance(value, str) and value.strip():
                return value.strip()

    for key in (
        "llm_explanation",
        "llm_response",
        "generated_response",
        "explanation",
    ):
        value = state.get(key)

        if isinstance(value, str) and value.strip():
            return value.strip()

    return ""


def _get_response_state(
    state: Dict[str, Any],
) -> Dict[str, Any]:
    """
    Preserve the existing response dictionary.

    LangGraph nodes must not accidentally discard the response
    generated by upstream nodes.
    """

    response = state.get("response")

    if isinstance(response, dict):
        return dict(response)

    return {}


# ============================================================
# EVIDENCE HELPERS
# ============================================================

def _get_evidence(
    state: Dict[str, Any],
) -> list[dict[str, Any]]:
    """
    Retrieve the evidence currently available in graph state.

    retrieved_evidence is the canonical RAG field.
    """

    for key in (
        "retrieved_evidence",
        "evidence",
        "retrieved_documents",
    ):
        value = state.get(key)

        if isinstance(value, list):
            return [
                item
                for item in value
                if isinstance(item, dict)
            ]

    return []


def _get_citations(
    state: Dict[str, Any],
) -> list[dict[str, Any]]:
    """
    Retrieve citation metadata from graph state.
    """

    citations = state.get("citations", [])

    if isinstance(citations, list):
        return [
            item
            for item in citations
            if isinstance(item, dict)
        ]

    return []


def _evidence_text(
    item: dict[str, Any],
) -> str:
    """
    Extract textual content from an evidence item.
    """

    for key in (
        "text",
        "page_content",
        "content",
        "chunk_text",
        "evidence",
        "source_text",
    ):
        value = item.get(key)

        if isinstance(value, str) and value.strip():
            return value.strip()

    return ""


def _citation_id(
    item: dict[str, Any],
) -> str:
    """
    Normalize an evidence/citation ID to E1, E2, etc.
    """

    raw = (
        item.get("citation_id")
        or item.get("id")
        or item.get("label")
        or ""
    )

    match = re.fullmatch(
        r"\[?\s*(E\d+)\s*\]?",
        str(raw).strip(),
        flags=re.IGNORECASE,
    )

    if match:
        return match.group(1).upper()

    return ""


# ============================================================
# THRESHOLD / METRIC HELPERS
# ============================================================

def _numeric_threshold(
    value: Any,
) -> float:
    """
    Normalize the evaluator's claim-support threshold.
    """

    if isinstance(value, bool):
        raise TypeError(
            "CLAIM_SUPPORT_THRESHOLD must be numeric, "
            f"received bool: {value!r}"
        )

    if isinstance(value, (int, float)):
        threshold = float(value)
    else:
        try:
            threshold = float(value)
        except (TypeError, ValueError) as exc:
            raise TypeError(
                "CLAIM_SUPPORT_THRESHOLD must be numeric, "
                f"received {type(value).__name__}: {value!r}"
            ) from exc

    if not 0.0 <= threshold <= 1.0:
        raise ValueError(
            "CLAIM_SUPPORT_THRESHOLD must be between 0 and 1, "
            f"received {threshold}"
        )

    return threshold


def _metric_float(
    result: dict[str, Any],
    key: str,
    default: float,
) -> float:
    """
    Safely extract a numeric evaluator metric.
    """

    try:
        value = result.get(key, default)

        if value is None:
            return float(default)

        return float(value)

    except (TypeError, ValueError):
        return float(default)


# ============================================================
# EVALUATION
# ============================================================

def _enrich_result(result: dict[str, Any]) -> dict[str, Any]:
    """
    Ensure every groundedness result (empty, original, or fallback)
    carries the same shape: `cited_claims` and the `thresholds` this
    node actually enforces (`evaluate_groundedness` only knows its own
    per-claim support threshold, not the node-level pass/fail policy).
    """

    claims = result.get("claims", [])

    result.setdefault(
        "cited_claims",
        sum(1 for claim in claims if claim.get("citation_ids")),
    )

    result.setdefault(
        "thresholds",
        {
            "groundedness_threshold": GROUNDEDNESS_THRESHOLD,
            "claim_support_threshold": _numeric_threshold(
                CLAIM_SUPPORT_THRESHOLD
            ),
            "max_unsupported_claim_rate": MAX_UNSUPPORTED_CLAIM_RATE,
        },
    )

    return result


def _evaluate(
    answer: str,
    citations: list[dict[str, Any]],
    evidence: list[dict[str, Any]],
) -> dict[str, Any]:
    """
    Evaluate an answer using the actual groundedness evaluator API.
    """

    threshold = _numeric_threshold(
        CLAIM_SUPPORT_THRESHOLD
    )

    result = evaluate_groundedness(
        answer=answer,
        citations=citations,
        evidence=evidence,
        threshold=threshold,
    )

    if not isinstance(result, dict):
        raise TypeError(
            "evaluate_groundedness returned "
            f"{type(result).__name__}, expected dict."
        )

    return _enrich_result(result)


def _passes(
    result: dict[str, Any],
    answer: str,
) -> bool:
    """
    Apply the strict project-level groundedness policy.
    """

    if not answer.strip():
        return False

    try:
        total_claims = int(
            result.get("total_claims", 0)
        )
    except (TypeError, ValueError):
        total_claims = 0

    if total_claims <= 0:
        return False

    groundedness_score = _metric_float(
        result,
        "groundedness_score",
        result.get("groundedness", 0.0),
    )

    citation_coverage = _metric_float(
        result,
        "citation_coverage",
        0.0,
    )

    unsupported_claim_rate = _metric_float(
        result,
        "unsupported_claim_rate",
        1.0,
    )

    return bool(
        groundedness_score >= GROUNDEDNESS_THRESHOLD
        and citation_coverage >= 1.0
        and unsupported_claim_rate <= MAX_UNSUPPORTED_CLAIM_RATE
    )


# ============================================================
# DETERMINISTIC FALLBACK
# ============================================================

MAX_FALLBACK_SENTENCES = 3


def _find_best_fallback(
    evidence: list[dict[str, Any]],
) -> str:
    """
    Construct a conservative, multi-sentence explanation directly from
    retrieved evidence -- a short paragraph rather than one terse line,
    so the fallback still reads as a complete explanation even though
    it's not the model's own generated text.

    Every sentence is either a template whose wording echoes known
    evidence phrasing, or a sentence drawn verbatim from its cited
    evidence chunk -- both are grounded by construction (guaranteed
    high lexical overlap with what they cite), unlike a generic
    templated sentence with no relation to whatever was retrieved.

    The fallback does not use model prediction, probability,
    uncertainty, OOD status, or individual feature interpretation.
    """

    normalized: list[tuple[str, str]] = []

    for item in evidence:
        citation_id = _citation_id(item)
        text = _evidence_text(item)

        if citation_id and text:
            normalized.append(
                (citation_id, text)
            )

    if not normalized:
        return ""

    sentences: list[str] = []
    used_citation_ids: set[str] = set()

    # ----------------------------------------------------------------
    # Preferred templates, in priority order: wording chosen to echo
    # common evidence phrasing so these score well on lexical overlap.
    # ----------------------------------------------------------------

    templates = [
        (
            ("positive screening result", "thorough assessment"),
            "A positive screening result should be followed by a thorough assessment.",
        ),
        (
            ("developmental screening", "developmental concerns"),
            "Developmental screening can help identify developmental concerns.",
        ),
    ]

    for keywords, sentence_text in templates:

        if len(sentences) >= MAX_FALLBACK_SENTENCES:
            break

        for citation_id, text in normalized:

            if citation_id in used_citation_ids:
                continue

            lowered = text.lower()

            if all(keyword in lowered for keyword in keywords):
                sentences.append(f"{sentence_text} [{citation_id}]")
                used_citation_ids.add(citation_id)
                break

    # ----------------------------------------------------------------
    # Fill any remaining slots with each unused evidence item's own
    # opening sentence, so the fallback draws on multiple distinct
    # sources rather than repeating one.
    # ----------------------------------------------------------------

    for citation_id, text in normalized:

        if len(sentences) >= MAX_FALLBACK_SENTENCES:
            break

        if citation_id in used_citation_ids:
            continue

        first_sentence = _first_sentence(text)

        if not first_sentence:
            continue

        sentences.append(f"{first_sentence} [{citation_id}]")
        used_citation_ids.add(citation_id)

    if not sentences:
        citation_id, _text = normalized[0]
        return (
            "The retrieved evidence provides general information "
            f"relevant to developmental screening. [{citation_id}]"
        )

    return " ".join(sentences)


_JUNK_PATTERNS = (
    re.compile(r"[�‘’“”]"),  # encoding artifacts (mojibake, smart quotes that failed to decode)
    re.compile(r"\d{1,2}/\d{1,2}/\d{2,4}"),  # scraped-page timestamps, e.g. "9/2/26, 6:12 PM"
    re.compile(r"\d{1,2}:\d{2}\s*(AM|PM)", re.IGNORECASE),
    re.compile(r"^https?://"),
)


def _looks_like_clean_sentence(part: str) -> bool:
    """Reject fragments that are structurally not a usable sentence:
    too short, not capitalized (usually a mid-clause continuation left
    by fixed-size chunking cutting across a sentence boundary), missing
    terminal punctuation (usually a heading), or containing scraped-page
    junk (timestamps, encoding artifacts) -- all observed directly in
    this knowledge base's PDF-extracted chunks."""

    if len(part) < 20 or part[-1] not in ".!?" or not part[0].isupper():
        return False

    if any(pattern.search(part) for pattern in _JUNK_PATTERNS):
        return False

    # A real sentence has more than one word after its first -- rules
    # out short Title Case headings ("Pediatric Developmental Screening
    # Flowchart") that happen to satisfy the checks above.
    if len(part.split()) < 5:
        return False

    return True


def _first_sentence(text: str, max_chars: int = 280) -> str:
    """
    Extract a short, citable opening sentence from an evidence chunk.

    Splits on newlines as well as sentence-ending punctuation: PDF
    chunk text often runs a section heading straight into the next
    sentence with only a newline between them ("Involving families in
    screening\nResearch indicates..."), and splitting on punctuation
    alone would return that heading+sentence run-on as one "sentence".

    Returns "" (rather than a best-effort guess) when nothing in the
    chunk looks like a genuine, clean sentence -- the caller then
    skips to the next evidence item instead of using a heading,
    timestamp, or mid-clause fragment as if it were a complete thought.
    """

    text = str(text or "").strip()

    if not text:
        return ""

    parts = re.split(r"(?<=[.!?])\s+|\n+", text)
    parts = [part.strip() for part in parts if part.strip()]

    for part in parts:
        if _looks_like_clean_sentence(part):
            if len(part) > max_chars:
                part = part[:max_chars].rsplit(" ", 1)[0] + "..."
            return part

    return ""


# ============================================================
# EMPTY / ERROR RESULT
# ============================================================

def _empty_result(
    status: str,
    response_state: Dict[str, Any],
    error: str | None = None,
) -> Dict[str, Any]:
    """
    Return a consistent failed evaluation while preserving
    the existing response state.
    """

    result: Dict[str, Any] = {
        "groundedness_score": 0.0,
        "groundedness": 0.0,
        "citation_coverage": 0.0,
        "unsupported_claim_rate": 1.0,
        "citation_precision": 0.0,
        "total_claims": 0,
        "supported_claims": 0,
        "unsupported_claims": 0,
        "cited_claims": 0,
        "claims": [],
        "passed": False,
        "thresholds": {
            "groundedness_threshold": GROUNDEDNESS_THRESHOLD,
            "claim_support_threshold": float(
                CLAIM_SUPPORT_THRESHOLD
            ),
            "max_unsupported_claim_rate": (
                MAX_UNSUPPORTED_CLAIM_RATE
            ),
        },
    }

    if error:
        result["error"] = error

    return {
        "response": response_state,
        "groundedness": result,
        "groundedness_status": status,
        "groundedness_passed": False,
        "groundedness_score": 0.0,
        "citation_coverage": 0.0,
        "citation_precision": 0.0,
        "unsupported_claim_rate": 1.0,
    }


# ============================================================
# LANGGRAPH NODE
# ============================================================

def groundedness_node(
    state: Dict[str, Any],
) -> Dict[str, Any]:
    """
    Evaluate the generated explanation against retrieved evidence.

    Pipeline:

        LLM explanation
              ↓
        groundedness evaluation
              ↓
        if failed
              ↓
        deterministic evidence fallback
              ↓
        re-evaluate fallback
              ↓
        continue with metrics describing the ACTUAL answer

    The node never changes:
        - prediction
        - probability
        - uncertainty
        - OOD status
        - routing
    """

    response_state = _get_response_state(state)

    response = _get_response(state)

    evidence = _get_evidence(state)

    citations = _get_citations(state)

    # --------------------------------------------------------
    # No generated explanation.
    # --------------------------------------------------------

    if not response:

        return _empty_result(
            "NO_RESPONSE",
            response_state,
        )

    # --------------------------------------------------------
    # No evidence.
    # --------------------------------------------------------

    if not evidence:

        return _empty_result(
            "NO_EVIDENCE",
            response_state,
        )

    # --------------------------------------------------------
    # Evaluate original LLM explanation.
    # --------------------------------------------------------

    try:

        original_result = _evaluate(
            answer=response,
            citations=citations,
            evidence=evidence,
        )

    except Exception as exc:

        return _empty_result(
            "ERROR",
            response_state,
            error=(
                f"{type(exc).__name__}: {exc}"
            ),
        )

    # --------------------------------------------------------
    # Original LLM explanation passed.
    # --------------------------------------------------------

    if _passes(
        original_result,
        response,
    ):

        original_result["passed"] = True

        original_result[
            "evaluation_target"
        ] = "llm_explanation"

        original_result[
            "fallback_used"
        ] = False

        response_state["llm_explanation"] = response
        response_state["fallback_used"] = False

        return {
            "response": response_state,
            "groundedness": original_result,
            "groundedness_status": "PASSED",
            "groundedness_passed": True,
            "groundedness_score": _metric_float(
                original_result,
                "groundedness_score",
                original_result.get(
                    "groundedness",
                    0.0,
                ),
            ),
            "citation_coverage": _metric_float(
                original_result,
                "citation_coverage",
                0.0,
            ),
            "citation_precision": _metric_float(
                original_result,
                "citation_precision",
                0.0,
            ),
            "unsupported_claim_rate": _metric_float(
                original_result,
                "unsupported_claim_rate",
                1.0,
            ),
        }

    # --------------------------------------------------------
    # Original LLM explanation failed.
    #
    # Preserve it for debugging/audit purposes.
    # --------------------------------------------------------

    response_state[
        "llm_explanation_rejected"
    ] = response

    response_state[
        "llm_explanation_rejection_reason"
    ] = (
        "LLM explanation failed groundedness validation."
    )

    # --------------------------------------------------------
    # Create deterministic fallback.
    # --------------------------------------------------------

    fallback = _find_best_fallback(
        evidence
    )

    if not fallback:

        original_result[
            "passed"
        ] = False

        original_result[
            "evaluation_target"
        ] = "llm_explanation"

        original_result[
            "fallback_used"
        ] = False

        response_state.setdefault("llm_explanation", response)

        return {
            "response": response_state,
            "groundedness": original_result,
            "groundedness_status": "FAILED",
            "groundedness_passed": False,
            "groundedness_score": _metric_float(
                original_result,
                "groundedness_score",
                original_result.get(
                    "groundedness",
                    0.0,
                ),
            ),
            "citation_coverage": _metric_float(
                original_result,
                "citation_coverage",
                0.0,
            ),
            "citation_precision": _metric_float(
                original_result,
                "citation_precision",
                0.0,
            ),
            "unsupported_claim_rate": _metric_float(
                original_result,
                "unsupported_claim_rate",
                1.0,
            ),
        }

    # --------------------------------------------------------
    # Evaluate the ACTUAL fallback answer.
    # --------------------------------------------------------

    try:

        fallback_result = _evaluate(
            answer=fallback,
            citations=citations,
            evidence=evidence,
        )

    except Exception as exc:

        original_result[
            "fallback_evaluation_error"
        ] = (
            f"{type(exc).__name__}: {exc}"
        )

        return {
            "response": response_state,
            "groundedness": original_result,
            "groundedness_status": "FAILED_FALLBACK",
            "groundedness_passed": False,
            "groundedness_score": _metric_float(
                original_result,
                "groundedness_score",
                original_result.get(
                    "groundedness",
                    0.0,
                ),
            ),
            "citation_coverage": _metric_float(
                original_result,
                "citation_coverage",
                0.0,
            ),
            "citation_precision": _metric_float(
                original_result,
                "citation_precision",
                0.0,
            ),
            "unsupported_claim_rate": _metric_float(
                original_result,
                "unsupported_claim_rate",
                1.0,
            ),
        }

    # --------------------------------------------------------
    # Fallback passed.
    #
    # IMPORTANT:
    # Replace the actual answer before final_audit.
    # --------------------------------------------------------

    if _passes(
        fallback_result,
        fallback,
    ):

        response_state[
            "llm_explanation"
        ] = fallback

        response_state[
            "generator"
        ] = "deterministic_grounded_fallback"

        # Keep the same status key used by llm_response.py.
        response_state[
            "llm_generation_status"
        ] = "REJECTED"

        response_state[
            "fallback_used"
        ] = True

        fallback_result[
            "passed"
        ] = True

        fallback_result[
            "evaluation_target"
        ] = "deterministic_grounded_fallback"

        fallback_result[
            "fallback_used"
        ] = True

        fallback_result[
            "original_llm_groundedness"
        ] = {
            "groundedness_score": _metric_float(
                original_result,
                "groundedness_score",
                original_result.get(
                    "groundedness",
                    0.0,
                ),
            ),
            "citation_coverage": _metric_float(
                original_result,
                "citation_coverage",
                0.0,
            ),
            "citation_precision": _metric_float(
                original_result,
                "citation_precision",
                0.0,
            ),
            "unsupported_claim_rate": _metric_float(
                original_result,
                "unsupported_claim_rate",
                1.0,
            ),
        }

        return {
            "response": response_state,
            "groundedness": fallback_result,
            "groundedness_status": "PASSED_FALLBACK",
            "groundedness_passed": True,
            "groundedness_score": _metric_float(
                fallback_result,
                "groundedness_score",
                fallback_result.get(
                    "groundedness",
                    0.0,
                ),
            ),
            "citation_coverage": _metric_float(
                fallback_result,
                "citation_coverage",
                0.0,
            ),
            "citation_precision": _metric_float(
                fallback_result,
                "citation_precision",
                0.0,
            ),
            "unsupported_claim_rate": _metric_float(
                fallback_result,
                "unsupported_claim_rate",
                1.0,
            ),
        }

    # --------------------------------------------------------
    # Fallback itself failed.
    #
    # Fail closed. Do not pretend it passed.
    # --------------------------------------------------------

    fallback_result[
        "passed"
    ] = False

    fallback_result[
        "evaluation_target"
    ] = "deterministic_grounded_fallback"

    fallback_result[
        "fallback_used"
    ] = False

    fallback_result[
        "original_llm_groundedness"
    ] = original_result

    response_state.setdefault("llm_explanation", fallback or response)

    return {
        "response": response_state,
        "groundedness": fallback_result,
        "groundedness_status": "FAILED_FALLBACK",
        "groundedness_passed": False,
        "groundedness_score": _metric_float(
            fallback_result,
            "groundedness_score",
            fallback_result.get(
                "groundedness",
                0.0,
            ),
        ),
        "citation_coverage": _metric_float(
            fallback_result,
            "citation_coverage",
            0.0,
        ),
        "citation_precision": _metric_float(
            fallback_result,
            "citation_precision",
            0.0,
        ),
        "unsupported_claim_rate": _metric_float(
            fallback_result,
            "unsupported_claim_rate",
            1.0,
        ),
    }


